import AppKit
import CoastlineCore
import SwiftUI

/// Coastline ▸ Settings… (⌘,)
struct SettingsView: View {
    @Environment(InventoryModel.self) private var inventory
    @State private var confirmReset = false
    @Bindable private var settings = AppSettings.shared

    var body: some View {
        TabView {
            Tab("General", systemImage: "gearshape") {
                Form {
                    Section("Accent colour") {
                        AccentPicker(selection: $settings.accent)
                    }
                    Section {
                        Picker("Appearance", selection: $settings.appearance) {
                            ForEach(AppSettings.Appearance.allCases) { Text($0.title).tag($0) }
                        }
                        .pickerStyle(.segmented)
                    }
                    Section {
                        Picker("Units", selection: $settings.units) {
                            ForEach(DisplayUnits.allCases) { Text($0.title).tag($0) }
                        }
                        .pickerStyle(.segmented)
                    } footer: {
                        Text("Applies to dimension fields and Machine Control positions, work coordinates and jogging.")
                    }
                    Section {
                        Button("Show “How Coastline Works” on Next Launch") {
                            UserDefaults.standard.set(false, forKey: "seenWelcome")
                        }
                    }
                }
                .formStyle(.grouped)
        .darkPanel()
                .scrollEdgeEffectStyle(.soft, for: .all)
            }
            Tab("Machining", systemImage: "gearshape.2") {
                Form {
                    Section {
                        Toggle("Reference bores on two-sided parts", isOn: $settings.referenceBores)
                    } footer: {
                        Text("Side A mills two small bores through the frame; after the flip, side B's zero is found from their centres (bore probing), not from the sawn or clamped edges. Repeatable to a few hundredths and works where an edge is out of reach.")
                    }
                    Section {
                        Picker("Engines generating at once", selection: $settings.engines) {
                            Text("Automatic (\(Self.autoEngines))").tag(0)
                            ForEach(1...6, id: \.self) { Text("\($0)").tag($0) }
                        }
                    } footer: {
                        Text("Toolpaths are generated by several engine processes side by side, one operation each. More is faster on many cores but takes more memory (about 300 MB each).")
                    }
                }
                .formStyle(.grouped)
        .darkPanel()
                .scrollEdgeEffectStyle(.soft, for: .all)
            }
            Tab("Inventory", systemImage: "shippingbox") {
                Form {
                    Section {
                        LabeledContent("File") {
                            Text(inventory.fileURL.path(percentEncoded: false))
                                .font(.callout.monospaced()).textSelection(.enabled).lineLimit(2).truncationMode(.middle)
                        }
                        HStack {
                            Button("Show in Finder") { NSWorkspace.shared.activateFileViewerSelecting([inventory.fileURL]) }
                            Spacer()
                            Button("Reset to Starter Inventory…", role: .destructive) { confirmReset = true }
                        }
                    } footer: {
                        Text("Your inventory is a plain JSON file. Coastline keeps the previous version next to it as Inventory.json.bak.")
                    }
                }
                .formStyle(.grouped)
        .darkPanel()
                .scrollEdgeEffectStyle(.soft, for: .all)
            }
            Tab("About", systemImage: "info.circle") {
                VStack(spacing: 10) {
                    Image(systemName: "water.waves").font(.system(size: 44)).foregroundStyle(Theme.accent)
                    Text("Coastline").font(.title.weight(.semibold))
                    Text("CAM and guided setups for the machine").foregroundStyle(.secondary)
                }
                .frame(maxWidth: .infinity, maxHeight: .infinity)
            }
        }
        .frame(width: 560, height: 420)
        .confirmationDialog("Replace your inventory with the starter inventory?", isPresented: $confirmReset) {
            Button("Replace", role: .destructive) { inventory.resetToStarter() }
        } message: {
            Text("The current inventory is kept as Inventory.json.bak until your next change.")
        }
    }

    private static var autoEngines: Int {
        let cores = ProcessInfo.processInfo.activeProcessorCount
        return cores >= 10 ? 4 : cores >= 8 ? 3 : 2
    }
}

/// The accent colours as a row of swatches, like System Settings' own.
struct AccentPicker: View {
    @Binding var selection: AppSettings.Accent
    @Environment(\.accessibilityReduceMotion) private var reduceMotion

    var body: some View {
        VStack(alignment: .leading, spacing: 10) {
            HStack(spacing: 10) {
                ForEach(AppSettings.Accent.allCases) { a in
                    Button { withAnimation(reduceMotion ? nil : .snappy) { selection = a } } label: {
                        Circle()
                            .fill(a.color.gradient)
                            .frame(width: 24, height: 24)
                            .overlay {
                                if selection == a { Circle().fill(.white).frame(width: 8, height: 8) }
                            }
                            .overlay(Circle().strokeBorder(.primary.opacity(0.15)))
                            .padding(3)
                            .overlay(Circle().strokeBorder(selection == a ? a.color : .clear, lineWidth: 2))
                    }
                    .buttonStyle(.plain)
                    .help(a.title)
                    .accessibilityLabel(a.title)
                    .accessibilityAddTraits(selection == a ? .isSelected : [])
                }
            }
            Text(selection.title).font(.callout).foregroundStyle(.secondary)
        }
        .padding(.vertical, 4)
    }
}
